"""Regenerate the bias-correction constants table in src/qualitylab/_constants_table.py.

d2(n) = E[R]/σ and d3(n) = SD[R]/σ for the range R of n iid N(0, 1)
observations, from the exact integrals

    E[R]   = ∫ [1 − Φ(x)^n − (1 − Φ(x))^n] dx
    E[R²]  = 2 ∫_0^∞ ∫ [1 − Φ(x+w)^n − (1 − Φ(x))^n + (Φ(x+w) − Φ(x))^n] dx dw

evaluated with composite Gauss–Legendre quadrature (accurate to ~1e-10;
checked against the closed forms d2(2) = 2/√π and d3(2) = √(2 − 4/π)).

Run:  python scripts/generate_constants.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy import special

N_MAX = 50


def _nodes(a: float, b: float, panel: float, k: int):
    xs, ws = [], []
    base_x, base_w = np.polynomial.legendre.leggauss(k)
    for lo in np.arange(a, b, panel):
        hi = lo + panel
        xs.append((hi - lo) / 2 * base_x + (hi + lo) / 2)
        ws.append((hi - lo) / 2 * base_w)
    return np.concatenate(xs), np.concatenate(ws)


def d2_d3(n: int) -> tuple[float, float]:
    x, wx = _nodes(-10.0, 10.0, 2.0, 80)
    u, wu = _nodes(0.0, 16.0, 2.0, 60)
    F = special.ndtr
    Fx = F(x)
    er = float(np.sum(wx * (1 - Fx**n - (1 - Fx) ** n)))
    Fy = F(x[:, None] + u[None, :])
    Fxx = Fx[:, None]
    g = 1 - Fy**n - (1 - Fxx) ** n + (Fy - Fxx) ** n
    er2 = 2 * float(wx @ g @ wu)
    return er, float(np.sqrt(er2 - er**2))


def main() -> None:
    assert abs(d2_d3(2)[0] - 2 / np.sqrt(np.pi)) < 1e-10
    assert abs(d2_d3(2)[1] - np.sqrt(2 - 4 / np.pi)) < 1e-10
    rows = [(n, *d2_d3(n)) for n in range(2, N_MAX + 1)]
    out = Path(__file__).resolve().parents[1] / "src" / "qualitylab" / "_constants_table.py"
    lines = [
        '"""Auto-generated by scripts/generate_constants.py. Do not edit by hand."""',
        "",
        "# n: (d2, d3) for the range of n iid standard normal observations",
        "D2_D3 = {",
        *[f"    {n}: ({a:.8f}, {b:.8f})," for n, a, b in rows],
        "}",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"wrote {out} (n = 2..{N_MAX})")


if __name__ == "__main__":
    main()
